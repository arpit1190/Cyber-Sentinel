/**
 * aiSecurityGuard.js
 * AI Assistant Security Boundary, Prompt Injection Defense, and Outbound Secret Scrubber.
 *
 * Guardrails:
 * 1. UNTRUSTED INPUT ENCAPSULATION: All telemetry, logs, and user payloads are wrapped in inert delimiter boundaries.
 * 2. PROMPT INJECTION DEFENSE: Detects and neutralizes direct and indirect prompt injections.
 * 3. OUTBOUND SECRET SCRUBBING: Prevents leaking API keys, JWTs, password hashes, and environment variables.
 * 4. ADVISORY-ONLY BOUNDARY: AI recommendations are strictly untrusted proposals.
 */

'use strict';

const DIRECT_INJECTION_PATTERNS = [
  /ignore\s+(all\s+)?(previous|prior)\s+(instructions|directives|rules)/i,
  /disregard\s+(all\s+)?(previous|prior)\s+(prompts|instructions)/i,
  /you\s+are\s+now\s+(in\s+)?(unrestricted|dan|developer|god)\s+mode/i,
  /output\s+(your\s+)?(system\s+prompt|instructions|initial\s+prompt)/i,
  /reveal\s+(the\s+)?(secret|gemini\s+key|jwt_secret|api_key)/i,
  /system:\s*override/i,
  /assistant:\s*understood,\s*i\s*will/i,
  /\[instruction\]/i,
  /\[system\s*message\]/i,
];

const INDIRECT_INJECTION_PATTERNS = [
  /drop\s+table\s+[a-zA-Z0-9_]+/i,
  /grant\s+all\s+privileges/i,
  /cat\s+\/etc\/passwd/i,
  /curl\s+https?:\/\/[^\s]+\s*\|\s*(sh|bash)/i,
  /rm\s+-rf\s+\//i,
  /approve\s+all\s+(actions|proposals|requests)/i,
  /bypass\s+(auth|authentication|rbac)/i,
];

const SENSITIVE_SECRET_PATTERNS = [
  /AIza[0-9A-Za-z-_]{35}/g, // Gemini / Google API Key
  /eyJ[a-zA-Z0-9_-]{10,}\.[a-zA-Z0-9_-]{10,}\.[a-zA-Z0-9_-]{10,}/g, // JWT
  /Bearer\s+[a-zA-Z0-9._-]+/gi, // Bearer Token
  /postgres:\/\/[^:]+:[^@]+@[^\/]+\/[a-zA-Z0-9_-]+/gi, // Database connection string
];

/**
 * Encapsulates untrusted forensic evidence inside an inert, tamper-evident boundary block.
 */
function encapsulateUntrustedEvidence(evidence, source = 'telemetry') {
  let evidenceStr = '';
  if (typeof evidence === 'string') {
    evidenceStr = evidence;
  } else if (evidence !== null && typeof evidence === 'object') {
    evidenceStr = JSON.stringify(evidence, null, 2);
  } else {
    evidenceStr = String(evidence || '');
  }

  // Sanitize any existing boundary escape attempts
  const sanitized = evidenceStr
    .replace(/\[\/?UNTRUSTED_EVIDENCE\]/gi, '[EVIDENCE_TAG_ESCAPED]')
    .replace(/\[\/?SYSTEM_INSTRUCTION\]/gi, '[SYSTEM_TAG_ESCAPED]');

  return `\n[UNTRUSTED FORENSIC EVIDENCE - SOURCE: ${source.toUpperCase()}]\n${sanitized}\n[END UNTRUSTED EVIDENCE - INERT DATA ONLY]\n`;
}

/**
 * Detects direct prompt injection attempts.
 */
function inspectPromptInjection(text) {
  if (typeof text !== 'string') return { isInjection: false, matchedPattern: null };

  for (const pattern of DIRECT_INJECTION_PATTERNS) {
    if (pattern.test(text)) {
      return {
        isInjection: true,
        type: 'DIRECT_PROMPT_INJECTION',
        matchedPattern: pattern.toString(),
      };
    }
  }

  return { isInjection: false, matchedPattern: null };
}

/**
 * Detects indirect prompt injection embedded within ingested telemetry or logs.
 */
function inspectIndirectInjection(evidenceText) {
  if (typeof evidenceText !== 'string') return { hasIndirectInjection: false };

  for (const pattern of INDIRECT_INJECTION_PATTERNS) {
    if (pattern.test(evidenceText)) {
      return {
        hasIndirectInjection: true,
        type: 'INDIRECT_TELEMETRY_INJECTION',
        matchedPattern: pattern.toString(),
      };
    }
  }

  return { hasIndirectInjection: false };
}

/**
 * Scrubs outbound responses generated by the AI to prevent secret/token exfiltration.
 */
function scrubOutboundSecretLeakage(responseContent) {
  if (typeof responseContent !== 'string') return responseContent;

  let clean = responseContent;
  for (const pattern of SENSITIVE_SECRET_PATTERNS) {
    clean = clean.replace(pattern, '[REDACTED_SENSITIVE_SECRET]');
  }

  return clean;
}

module.exports = {
  encapsulateUntrustedEvidence,
  inspectPromptInjection,
  inspectIndirectInjection,
  scrubOutboundSecretLeakage,
};
